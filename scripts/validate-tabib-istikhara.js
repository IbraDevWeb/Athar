#!/usr/bin/env node
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const data=read('tabib_data.js'),detail=read('js/components/TabibDetailView.js');
const html=read('index.html'),sw=read('service-worker.js'),config=read('js/config.js');
new vm.Script(data,{filename:'tabib_data.js'});new vm.Script(detail,{filename:'TabibDetailView.js'});
const cards=vm.runInNewContext(data+'\nTABIB_DATA');
assert.equal(cards.length,50,'Les 50 fiches initiales doivent être conservées');
assert.equal(new Set(cards.map(c=>c.id)).size,50,'Les identifiants doivent rester uniques');
assert.deepEqual(Array.from(cards,c=>c.id),Array.from({length:50},(_,i)=>i+1),'Ordre du corpus modifié');
const item=cards.find(c=>c.id===8);
assert.ok(item,'Fiche istikhâra absente');
assert.match(item.title,/istikhâra/i);
assert.ok(item.hadith.ar.length>500 && item.hadith.fr.length>400,'Invocation complète ou traduction absente');
assert.ok(!item.hadith.ar.includes('...')&&!item.hadith.phonetic.includes('...'),'Invocation encore abrégée');
assert.ok(item.hadith.ar.includes('ثُمَّ أَرْضِنِي بِهِ'),'Fin de l’invocation absente');
assert.equal(item.hadith.sourceUrl,'https://sunnah.com/bukhari:1166');
assert.ok(item.hadith.source.includes('1166'),'Référence primaire imprécise');
assert.ok(item.hadith.translationNote.includes('Traduction du sens'),'Traduction non contextualisée');
assert.match(item.quran.ref,/3:159/);
assert.equal(item.actions.length,5);
assert.equal(item.learning.questions.length,5);
assert.equal(item.learning.glossary.length,5);
assert.equal(item.learning.sources.length,4);
assert.ok(item.learning.questions.some(x=>/rêve/.test(x.question)),'Question des rêves absente');
assert.ok(item.learning.questions.some(x=>/porte fermée/.test(x.question)),'Superstitions des signes non abordées');
for(const source of item.learning.sources)assert.ok(/^https:\/\//.test(source.url)&&source.label,'Sources non vérifiables');
// Empreinte FNV1a calculée sur les 49 cartes hors numéro 8, identiques au fichier avant modification.
const first=data.indexOf('            {\r\n                id: 8,');
const next=data.indexOf('            {\r\n                id: 9,',first);
assert.ok(first>=0&&next>first,'Découpage des fiches historiques impossible');
const others=data.slice(0,first)+data.slice(next);
let h=2166136261;
for(let i=0;i<others.length;i++)h=Math.imul(h^others.charCodeAt(i),16777619)>>>0;
assert.equal(h.toString(16),'bf68eb6f','Une autre fiche Tabib a été modifiée');
for(const token of ['v-if="remedy.learning"','remedy.learning.questions','remedy.learning.glossary','remedy.learning.sources','remedy.hadith.sourceUrl','remedy.hadith.translationNote','rel="noopener noreferrer"'])assert.ok(detail.includes(token),'Vue enrichie incomplète : '+token);
assert.ok(html.includes('tabib_data.js?v=athar-istikhara-v1'),'Données non actualisées');
assert.ok(html.includes('TabibDetailView.js?v=athar-tabib-no-essence-v1'),'Lecteur non actualisé');
assert.ok(sw.includes('tabib_data.js?v=athar-istikhara-v1'),'Données absentes du cache versionné');
assert.ok(sw.includes('TabibDetailView.js?v=athar-tabib-no-essence-v1'),'Composant absent du cache versionné');
assert.ok(config.includes("const APP_VERSION = 'athar-pro-v82-fiqh-maliki-intro-v1'"));
assert.ok(sw.includes("const CACHE_VERSION = 'athar-pro-v82-fiqh-maliki-intro-v1'"));
console.log('Tabib Istikhâra : invocation entière, 5 étapes, 5 FAQ, 5 notions, 4 sources ; 49 autres fiches inchangées.');
